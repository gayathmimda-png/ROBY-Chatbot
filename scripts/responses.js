// Regex helper for word boundaries
function matchesRegex(text, pattern) {
    const regex = new RegExp(`\\b${pattern}\\b`, 'i');
    return regex.test(text);
}

// Input Categories Engine
function getBotResponse(input) {
    if (!input || typeof input !== 'string') return "Sorry! Did not get it.";
    
    const cleanInput = input.trim().toLowerCase();

    // Word boundary matched greetings
    if (matchesRegex(cleanInput, 'hi') || matchesRegex(cleanInput, 'hello') || matchesRegex(cleanInput, 'hey')) {
        return hi[Math.floor(Math.random() * hi.length)];
    }

    // Intro
    if (cleanInput.includes('who are you') || cleanInput.includes('may i know who you are')) {
        return intro[Math.floor(Math.random() * intro.length)];
    }

    // Name
    if (cleanInput.includes('what is your name') || cleanInput.includes('do you have a name')) {
        return MyName[Math.floor(Math.random() * MyName.length)];
    }

    // Greetings
    if (cleanInput.includes('how are you') || cleanInput.includes("what's up") || cleanInput.includes("what's going on") || cleanInput.includes("how's it going")) {
        return greetings[Math.floor(Math.random() * greetings.length)];
    }

    // Fine
    if (matchesRegex(cleanInput, 'fine') || cleanInput.includes('i am good') || cleanInput.includes('pretty good')) {
        return fine[Math.floor(Math.random() * fine.length)];
    }

    // WhatCan
    if (cleanInput.includes('what can you do') || cleanInput.includes('can you help')) {
        return WhatCan[Math.floor(Math.random() * WhatCan.length)];
    }

    // Purpose
    if (cleanInput.includes('purpose of education')) {
        return purpose[Math.floor(Math.random() * purpose.length)];
    }

    // OnlineEdu
    if (cleanInput.includes('learn during covid') || cleanInput.includes('learn during pandemic') || cleanInput.includes('online learn') || cleanInput.includes('online education') || cleanInput.includes('online study')) {
        return OnlineEdu[Math.floor(Math.random() * OnlineEdu.length)];
    }

    // Hobbies
    if (cleanInput.includes('hobby') || cleanInput.includes('hobbies')) {
        return hobbies[Math.floor(Math.random() * hobbies.length)];
    }

    // Thank
    if (cleanInput.includes('thank')) {
        return thank[Math.floor(Math.random() * thank.length)];
    }

    // ChatEnd
    if (matchesRegex(cleanInput, 'bye') || cleanInput.includes('see you')) {
        return ChatEnd[Math.floor(Math.random() * ChatEnd.length)];
    }

    // WebDesign
    if (cleanInput.includes('web design')) {
        if (cleanInput.includes('learn')) {
            return WebDesignLearn[Math.floor(Math.random() * WebDesignLearn.length)];
        } else if (cleanInput.includes('course')) {
            return WebDesignCourse[Math.floor(Math.random() * WebDesignCourse.length)];
        } else if (cleanInput.includes('earn money') || cleanInput.includes('make money')) {
            return WebDesignMoney[Math.floor(Math.random() * WebDesignMoney.length)];
        } else if (matchesRegex(cleanInput, 'become') || cleanInput.includes('career') || matchesRegex(cleanInput, 'be')) {
            return WebDesignBecome[Math.floor(Math.random() * WebDesignBecome.length)];
        } else {
            return WebDesign[Math.floor(Math.random() * WebDesign.length)];
        }
    }

    // WebDevelop
    if (cleanInput.includes('web develop')) {
        if (cleanInput.includes('learn')) {
            return WebDevelopLearn[Math.floor(Math.random() * WebDevelopLearn.length)];
        } else if (cleanInput.includes('course')) {
            return WebDevelopCourse[Math.floor(Math.random() * WebDevelopCourse.length)];
        } else if (cleanInput.includes('earn money') || cleanInput.includes('make money')) {
            return WebDevelopMoney[Math.floor(Math.random() * WebDevelopMoney.length)];
        } else if (matchesRegex(cleanInput, 'become') || cleanInput.includes('career') || matchesRegex(cleanInput, 'be')) {
            return WebDevelopBecome[Math.floor(Math.random() * WebDevelopBecome.length)];
        } else {
            return WebDevelop[Math.floor(Math.random() * WebDevelop.length)];
        }
    }
    
    // Fallback search link formatting
    const searchUrl = `https://www.google.com/search?q=${encodeURIComponent(cleanInput)}`;
    return `Sorry! Did not get it. Still I am learning humans' languages. But I provide a Google search related to your question.<br><br><a href="${searchUrl}" target="_blank" class="resource-card">Search "${input}" on Google <i class="fa fa-search"></i></a>`;
}

